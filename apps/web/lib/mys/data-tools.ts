import type { MysRole } from './contract'
import type { MysDataCard } from './data-cards'
import { readMysStudentSummary, MysSummaryError } from './student-summary'

export const mysDataTools = [
  { name: 'resumir_acompanhamento', description: 'Exclusivo do Personal: resumo atual de aluno com vínculo ativo, com contagens exatas de sessões concluídas em 7/30 dias corridos, último treino, fichas ativas e avaliações.', properties: { aluno_id: { type: 'string', description: 'UUID do aluno autorizado.' } }, required: ['aluno_id'] },
  { name: 'resumo_shapeos', description: 'Consulta contagens atuais. Admin: usuários por perfil e status, fichas e sessões nos últimos 30 dias. Personal: seus vínculos ativos e suas fichas.', properties: {}, required: [] },
  { name: 'buscar_alunos', description: 'Busca alunos por nome, somente dentro do acesso do usuário. Retorna até 20 resultados e a contagem total. Use nome vazio para listar. Nunca escolha entre homônimos sem perguntar.', properties: { nome: { type: 'string', description: 'Nome ou parte do nome; vazio para listar.' } }, required: ['nome'] },
  { name: 'consultar_aluno', description: 'Consulta aluno autorizado, suas fichas, últimas 10 sessões, últimas 5 avaliações físicas e próximos 10 treinos agendados. Use o ID retornado pela busca.', properties: { aluno_id: { type: 'string', description: 'UUID do aluno retornado por buscar_alunos.' } }, required: ['aluno_id'] },
  { name: 'consultar_treino', description: 'Consulta ficha autorizada com até 50 exercícios, séries, repetições, descanso e prescrição. Use o ID retornado por consultar_aluno.', properties: { treino_id: { type: 'string', description: 'UUID da ficha.' } }, required: ['treino_id'] },
].map(({ name, description, properties, required }) => ({ type: 'function', function: { name, description, parameters: { type: 'object', properties, required, additionalProperties: false } } }))

const labels: Record<string, string> = { resumir_acompanhamento: 'Acompanhamento do aluno: frequência, fichas e avaliações', resumo_shapeos: 'Resumo da ShapeOS', buscar_alunos: 'Alunos', consultar_aluno: 'Fichas, sessões e evolução do aluno', consultar_treino: 'Exercícios e prescrição da ficha' }
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
type CountQuery = PromiseLike<{ count: number | null; error: unknown }> & { abortSignal(signal: AbortSignal): CountQuery }

// Only fixed SELECT queries using the signed-in user's client. No service key,
// SQL generated by the model, arbitrary tables, or database mutations.
export function createMysDataReader(db: SupabaseClient, access: { id: string; role: MysRole }, signal: AbortSignal, selectedStudentId?: string) {
  if (access.role === 'ALUNO') return createStudentMysReader(db, access, signal)
  const admin = access.role === 'ADMIN'
  const sources = new Set<string>()
  const cards: MysDataCard[] = []
  const timed = <T extends { abortSignal(signal: AbortSignal): T }>(query: T) => query.abortSignal(signal)
  const checked = (result: { data: unknown; error: unknown }) => {
    if (result.error) throw new Error('Não foi possível consultar estes dados. Não interprete como resultado vazio.')
    return result.data
  }
  async function allowedStudent(id: string) {
    if (selectedStudentId && id !== selectedStudentId) throw new MysSummaryError(403, 'Inicie outra conversa para consultar outro aluno.')
    if (admin) return
    const result = await timed(db.from('personal_alunos').select('aluno_id').eq('personal_id', access.id).eq('aluno_id', id).eq('status', 'ATIVO')).maybeSingle()
    if (!checked(result)) throw new Error('Aluno não encontrado ou fora do seu acesso.')
  }
  async function count(query: CountQuery): Promise<number> {
    const result = await timed(query)
    if (result.error || typeof result.count !== 'number') throw new Error('Contagem indisponível. Não invente um total.')
    return result.count
  }
  async function run(name: string, raw: string) {
    try {
      if (!Object.hasOwn(labels, name) || raw.length > 2000) throw new Error('Consulta não permitida.')
      const args = JSON.parse(raw)
      if (!args || typeof args !== 'object' || Array.isArray(args)) throw new Error('Argumentos inválidos.')
      const definition = mysDataTools.find(tool => tool.function.name === name)!
      const allowedArgs = new Set<string>(definition.function.parameters.required)
      if (Object.keys(args).some(key => !allowedArgs.has(key))) throw new Error('Argumentos não permitidos.')
      let data: unknown
      const pendingCards: MysDataCard[] = []
      if (name === 'resumir_acompanhamento') {
        if (admin) throw new MysSummaryError(403, 'Este resumo está disponível na conta do Personal.')
        if (typeof args.aluno_id !== 'string' || !uuid.test(args.aluno_id)) throw new Error('ID de aluno inválido.')
        if (selectedStudentId && args.aluno_id !== selectedStudentId) throw new MysSummaryError(403, 'Inicie outra conversa para consultar outro aluno.')
        const summary = await readMysStudentSummary(db, access.id, args.aluno_id, signal)
        data = summary
        pendingCards.push({ kind: 'student', title: summary.aluno.nome, detail: 'Acompanhamento consultado agora · dias corridos', metrics: [
          { label: 'Sessões em 7 dias', value: String(summary.frequencia.sessoesConcluidas7Dias) },
          { label: 'Sessões em 30 dias', value: String(summary.frequencia.sessoesConcluidas30Dias) },
          { label: 'Fichas ativas', value: String(summary.totalFichasAtivas) },
        ] })
      } else if (name === 'resumo_shapeos') {
        if (admin) {
          const queries = [
            ...['ADMIN','PERSONAL','ALUNO'].map(tipo => count(db.from('usuarios').select('id', { count: 'exact', head: true }).eq('tipo', tipo))),
            ...['ATIVO','PENDENTE','BLOQUEADO'].map(status => count(db.from('usuarios').select('id', { count: 'exact', head: true }).eq('status_conta', status))),
            count(db.from('treinos').select('id', { count: 'exact', head: true }).eq('ativo', true)),
            count(db.from('sessoes_treino').select('id', { count: 'exact', head: true }).eq('status','CONCLUIDO').gte('inicio', new Date(Date.now() - 30 * 86400000).toISOString())),
          ]
          const [admins, personals, alunos, ativos, pendentes, bloqueados, fichasAtivas, sessoesConcluidas30Dias] = await Promise.all(queries)
          data = { usuarios: { admins, personals, alunos, ativos, pendentes, bloqueados }, fichasAtivas, sessoesConcluidas30Dias }
          pendingCards.push({ kind:'summary', title:'Panorama da ShapeOS', detail:'Dados atuais da plataforma', metrics:[{label:'Alunos',value:String(alunos)},{label:'Personals',value:String(personals)},{label:'Fichas ativas',value:String(fichasAtivas)},{label:'Sessões em 30 dias',value:String(sessoesConcluidas30Dias)}] })
        } else {
          const [alunosVinculadosAtivos, fichasAtivas] = await Promise.all([
            count(db.from('personal_alunos').select('id', { count: 'exact', head: true }).eq('personal_id', access.id).eq('status', 'ATIVO')),
            count(db.from('treinos').select('id', { count: 'exact', head: true }).eq('personal_id', access.id).eq('ativo', true)),
          ])
          data = { alunosVinculadosAtivos, fichasAtivas, escopo: 'Somente seus vínculos e suas fichas.' }
          pendingCards.push({ kind:'summary',title:'Seu acompanhamento',detail:'Seus vínculos e suas fichas',metrics:[{label:'Alunos vinculados',value:String(alunosVinculadosAtivos)},{label:'Fichas ativas',value:String(fichasAtivas)}] })
        }
      } else if (name === 'buscar_alunos') {
        if (typeof args.nome !== 'string' || args.nome.length > 80) throw new Error('Nome inválido.')
        const pattern = `%${args.nome.trim().replace(/[\\%_]/g, '\\$&')}%`
        if (admin) {
          const result = await timed(db.from('usuarios').select('id,nome,status_conta', { count: 'exact' }).eq('tipo', 'ALUNO').ilike('nome', pattern).order('nome').order('id').limit(20))
          data = { alunos: checked(result), total: result.count, limite: 20 }
          for (const aluno of (result.data || []).slice(0,4)) pendingCards.push({kind:'student',title:aluno.nome,detail:`Conta ${String(aluno.status_conta).toLowerCase()}`,prompt:`Consulte no banco o aluno ${aluno.id} e resuma suas fichas e evolução registrada.`})
        } else {
          let query = db.from('personal_alunos').select('aluno:usuarios!personal_alunos_aluno_id_fkey!inner(id,nome,status_conta)', { count: 'exact' }).eq('personal_id', access.id).eq('status', 'ATIVO').ilike('aluno.nome', pattern).order('aluno_id').limit(20)
          if (selectedStudentId) query = query.eq('aluno_id', selectedStudentId)
          const result = await timed(query)
          checked(result)
          data = { alunos: (result.data || []).map(row => row.aluno), total: result.count, limite: 20 }
          for (const row of (result.data || []).slice(0,4)) {
            const aluno = Array.isArray(row.aluno) ? row.aluno[0] : row.aluno
            if (aluno) pendingCards.push({kind:'student',title:aluno.nome,detail:`Conta ${String(aluno.status_conta).toLowerCase()}`,prompt:`Consulte no banco o aluno ${aluno.id} e resuma suas fichas e evolução registrada.`})
          }
        }
      } else if (name === 'consultar_aluno') {
        if (typeof args.aluno_id !== 'string' || !uuid.test(args.aluno_id)) throw new Error('ID de aluno inválido.')
        await allowedStudent(args.aluno_id)
        const profile = await timed(db.from('usuarios').select('id,nome,status_conta').eq('id', args.aluno_id).eq('tipo', 'ALUNO')).maybeSingle()
        const aluno = checked(profile)
        if (!aluno) throw new Error('Aluno não encontrado ou fora do seu acesso.')
        let workouts = db.from('treinos').select('id,titulo,ativo,criado_em', { count: 'exact' }).eq('aluno_id',args.aluno_id)
        if (!admin) workouts = workouts.eq('personal_id',access.id)
        const [fichas,sessoes,avaliacoes,agenda] = await Promise.all([
          timed(workouts.order('criado_em',{ ascending: false }).limit(20)),
          timed(db.from('sessoes_treino').select('titulo,inicio,fim,status').eq('aluno_id',args.aluno_id).order('inicio',{ ascending: false }).limit(10)),
          timed(db.from('avaliacoes_fisicas').select('data,peso,cintura,quadril,braco').eq('aluno_id',args.aluno_id).order('data',{ ascending: false }).limit(5)),
          timed(db.from('agenda_treino').select('treino_id,data').eq('aluno_id',args.aluno_id).gte('data',new Date().toISOString().slice(0,10)).order('data').limit(10)),
        ])
        data = { aluno, fichas: checked(fichas), totalFichas: fichas.count, sessoesRecentes: checked(sessoes), avaliacoesRecentes: checked(avaliacoes), proximosAgendamentos: checked(agenda), limites: { fichas:20, sessoes:10, avaliacoes:5, agenda:10 } }
        for (const ficha of (fichas.data || []).slice(0,3)) pendingCards.push({kind:'workout',title:ficha.titulo,detail:ficha.ativo ? 'Ficha ativa' : 'Ficha inativa',prompt:`Consulte a ficha ${ficha.id} e analise seus exercícios e prescrição.`})
      } else {
        if (typeof args.treino_id !== 'string' || !uuid.test(args.treino_id)) throw new Error('ID de treino inválido.')
        let query = db.from('treinos').select('id,aluno_id,titulo,ativo').eq('id',args.treino_id)
        if (!admin) query = query.eq('personal_id',access.id)
        const result = await timed(query).maybeSingle()
        checked(result)
        if (!result.data) throw new Error('Ficha não encontrada ou fora do seu acesso.')
        await allowedStudent(result.data.aluno_id)
        const items = await timed(db.from('itens_treino').select('series,repeticoes,descanso_segundos,ordem,exercicio:exercicios(nome,grupo_muscular,equipamento),prescricao:prescricoes_treino(carga_alvo,duracao_segundos,rpe_alvo,superset,aquecimento,incremento_kg)', { count:'exact' }).eq('treino_id',args.treino_id).order('ordem').limit(50))
        data = { ficha: result.data, exercicios: checked(items), totalExercicios: items.count, limite:50 }
        pendingCards.push({kind:'workout',title:result.data.titulo,detail:result.data.ativo ? 'Ficha ativa' : 'Ficha inativa',metrics:[{label:'Exercícios',value:String(items.count ?? (items.data || []).length)}]})
      }
      const output = JSON.stringify({ consultadoEm: new Date().toISOString(), escopo: admin ? 'ADMIN' : 'PERSONAL: seus alunos e treinos', dados: data })
      if (output.length > 32000) throw new Error('Resultado grande demais. Faça uma consulta mais específica.')
      sources.add(labels[name])
      for (const card of pendingCards) if (cards.length < 8 && !cards.some(existing => existing.kind === card.kind && existing.title === card.title && existing.detail === card.detail && existing.prompt === card.prompt)) cards.push(card)
      return output
    } catch (error) {
      return JSON.stringify({ erro: error instanceof Error && !/JSON/.test(error.message) ? error.message : 'Consulta inválida.', dados: null, status: error instanceof MysSummaryError ? error.status : undefined })
    }
  }
  return { run, sources, cards }
}


export const mysStudentTools = [
 { type:'function', function:{ name:'resumo_meu_acompanhamento',description:'Consulta somente os registros do Aluno autenticado: fichas ativas, sessões concluídas em 7/30 dias corridos, últimas 5 sessões e avaliações e próximos 10 agendamentos.',parameters:{type:'object',properties:{},required:[],additionalProperties:false}}},
 { type:'function', function:{ name:'consultar_meu_treino',description:'Lê uma ficha ativa pertencente ao Aluno autenticado, com sua prescrição original. Use o ID retornado no resumo; não altera a ficha.',parameters:{type:'object',properties:{treino_id:{type:'string'}},required:['treino_id'],additionalProperties:false}}},
]
function createStudentMysReader(db:SupabaseClient,access:{id:string;role:MysRole},signal:AbortSignal) {
 const sources=new Set<string>(),cards:MysDataCard[]=[]
 const checked=(r:{data:unknown;error:unknown})=>{if(r.error)throw new Error('Consulta indisponível. Não interprete como ausência de registros.');return r.data}
 async function run(name:string,raw:string) {
  try {
   if(raw.length>2000)throw new Error('Consulta não permitida.')
   const args=JSON.parse(raw)
   if(!args||typeof args!=='object'||Array.isArray(args))throw new Error('Argumentos inválidos.')
   let data:unknown,label:string
   if(name==='resumo_meu_acompanhamento') {
    if(Object.keys(args).length)throw new Error('A identidade do Aluno é definida pelo servidor.')
    const now=new Date(),start=(days:number)=>new Date(now.getTime()-days*86400000).toISOString()
    const results=await Promise.all([
     db.from('treinos').select('id,titulo',{count:'exact'}).eq('aluno_id',access.id).eq('ativo',true).order('criado_em',{ascending:false}).limit(20).abortSignal(signal),
     ...[7,30].map(days=>db.from('sessoes_treino').select('id',{count:'exact',head:true}).eq('aluno_id',access.id).eq('status','CONCLUIDO').gte('inicio',start(days)).lte('inicio',now.toISOString()).abortSignal(signal)),
     db.from('sessoes_treino').select('titulo,inicio,fim,status').eq('aluno_id',access.id).order('inicio',{ascending:false}).limit(5).abortSignal(signal),
     db.from('avaliacoes_fisicas').select('data,peso,cintura,quadril,braco').eq('aluno_id',access.id).order('data',{ascending:false}).limit(5).abortSignal(signal),
     db.from('agenda_treino').select('treino_id,data').eq('aluno_id',access.id).gte('data',`${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,'0')}-${String(now.getDate()).padStart(2,'0')}`).order('data').limit(10).abortSignal(signal),
    ])
    results.forEach(checked)
    if(results.slice(0,3).some(r=>typeof r.count!=='number'))throw new Error('Contagem indisponível.')
    data={fichasAtivas:results[0].data,totalFichasAtivas:results[0].count,sessoesConcluidas7Dias:results[1].count,sessoesConcluidas30Dias:results[2].count,sessoesRecentes:results[3].data,avaliacoesRecentes:results[4].data,proximosTreinos:results[5].data,limites:{fichas:20,sessoes:5,avaliacoes:5,agenda:10},periodo:'Dias corridos; as listas recentes não representam todo o histórico.'}
    label='Seu acompanhamento na ShapeOS'
   } else if(name==='consultar_meu_treino') {
    if(Object.keys(args).some(k=>k!=='treino_id')||typeof args.treino_id!=='string'||!uuid.test(args.treino_id))throw new Error('Ficha inválida.')
    const result=await db.from('treinos').select('id,titulo,itens_treino(series,repeticoes,descanso_segundos,ordem,exercicio:exercicios(nome,grupo_muscular),prescricao:prescricoes_treino(carga_alvo,duracao_segundos,rpe_alvo,superset,aquecimento,observacoes))').eq('id',args.treino_id).eq('aluno_id',access.id).eq('ativo',true).abortSignal(signal).maybeSingle()
    data=checked(result);if(!data)throw new Error('Ficha indisponível ou fora do seu acesso.')
    label='Sua ficha e prescrição do Personal'
   } else throw new Error('Ferramenta fora do acesso do Aluno.')
   const result=JSON.stringify({consultadoEm:new Date().toISOString(),escopo:'ALUNO: somente seus registros',dados:data})
   if(result.length>32000)throw new Error('Consulta muito extensa. Peça uma informação mais específica.')
   sources.add(label);return result
  }catch(error){return JSON.stringify({erro:error instanceof Error?error.message:'Consulta indisponível.',dados:null})}
 }
 return {run,sources,cards}
}
